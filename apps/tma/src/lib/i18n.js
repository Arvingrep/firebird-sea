export function createI18n(initial = 'zh') {
  let lang = initial in MESSAGES ? initial : 'zh';
  return {
    get lang() { return lang; },
    setLang(l) { if (l in MESSAGES) lang = l; },
    t(key) { return MESSAGES[lang][key] ?? MESSAGES.zh[key] ?? key; },
  };
}

