// Generate a whitelist of non-secret PHP configuration literals; never execute PHP.
package main

import (
	"encoding/json"
	"flag"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"regexp"
	"strconv"
	"strings"
)

func main() {
	root := flag.String("root", "../../../..", "repository root")
	out := flag.String("out", "config_gen.go", "output")
	flag.Parse()
	if e := generate(*root, *out); e != nil {
		fmt.Fprintln(os.Stderr, e)
		os.Exit(1)
	}
}
func generate(root, out string) error {
	dir := filepath.Join(root, "webroot/include/config")
	read := func(file string) (map[string]string, error) {
		b, e := os.ReadFile(file)
		if e != nil {
			return nil, e
		}
		m := map[string]string{}
		re := regexp.MustCompile(`(?m)^\$([A-Za-z_][A-Za-z_0-9]*)\s*=\s*('(?:[^'\\]|\\.)*'|"(?:[^"\\]|\\.)*"|[0-9]+)\s*;`)
		for _, v := range re.FindAllStringSubmatch(string(b), -1) {
			s := v[2]
			if s[0] == '\'' || s[0] == '"' {
				s = s[1 : len(s)-1]
				s = strings.ReplaceAll(s, `\'`, `'`)
				s = strings.ReplaceAll(s, `\\`, `\`)
			}
			m[v[1]] = s
		}
		return m, nil
	}
	site, e := read(filepath.Join(dir, "siteConfig.inc.php"))
	if e != nil {
		return e
	}
	for _, k := range []string{"cfg_urlRewrite", "cfg_httpSecureAccess", "cfg_uploadDir", "cfg_ftpType", "cfg_ftpState", "cfg_remoteFtpUnify"} {
		if _, ok := site[k]; !ok {
			return fmt.Errorf("missing literal %s", k)
		}
	}
	number := func(m map[string]string, k string) int { n, _ := strconv.Atoi(m[k]); return n }
	storage := func(m map[string]string, prefix string) map[string]any {
		return map[string]any{"Type": number(m, prefix+"ftpType"), "State": number(m, prefix+"ftpState"), "URL": m[prefix+"ftpUrl"], "Dir": m[prefix+"ftpDir"], "OSS": m[prefix+"OSSUrl"], "Qiniu": m[prefix+"QINIUdomain"], "OBS": m[prefix+"OBSUrl"], "COS": m[prefix+"COSUrl"], "UploadDir": strings.ReplaceAll(m[prefix+"uploadDir"], "../", "")}
	}
	modules := map[string]any{}
	files, e := filepath.Glob(filepath.Join(dir, "*.inc.php"))
	if e != nil {
		return e
	}
	for _, f := range files {
		m, e := read(f)
		if e != nil {
			return e
		}
		name := strings.TrimSuffix(filepath.Base(f), ".inc.php")
		if name == "article" {
			for _, k := range []string{"customSubDomain", "custom_listRule", "custom_detailRule"} {
				if _, ok := m[k]; !ok {
					return fmt.Errorf("missing literal %s", k)
				}
			}
		}
		modules[name] = map[string]any{"SubDomain": number(m, "customSubDomain"), "ListRule": number(m, "custom_listRule"), "DetailRule": number(m, "custom_detailRule"), "CustomFTP": m["customFtp"] == "1", "CustomUpload": m["customUpload"] == "1", "Storage": storage(m, "custom_")}
	}
	local := map[string]bool{}
	for _, sub := range []string{"static", "uploads"} {
		base := filepath.Join(root, "webroot", sub)
		if _, e := os.Stat(base); os.IsNotExist(e) {
			continue
		}
		e = filepath.WalkDir(base, func(path string, d os.DirEntry, e error) error {
			if e != nil {
				return e
			}
			if !d.IsDir() && d.Type().IsRegular() && !strings.HasPrefix(d.Name(), ".") {
				rel, e := filepath.Rel(filepath.Join(root, "webroot"), path)
				if e != nil {
					return e
				}
				local["/"+filepath.ToSlash(rel)] = true
			}
			return nil
		})
		if e != nil {
			return e
		}
	}
	c := map[string]any{"Secure": site["cfg_httpSecureAccess"] == "1", "Rewrite": site["cfg_urlRewrite"] == "1", "RemoteUnify": site["cfg_remoteFtpUnify"] == "1", "Storage": storage(site, "cfg_"), "Modules": modules, "LocalFiles": local}
	b, e := json.Marshal(c)
	if e != nil {
		return e
	}
	src, e := format.Source([]byte("// Code generated by go generate; DO NOT EDIT.\npackage fburl\nconst generatedConfig = " + strconv.Quote(string(b)) + "\n"))
	if e != nil {
		return e
	}
	return os.WriteFile(out, src, 0644)
}
